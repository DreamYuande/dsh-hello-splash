import { readFileSync, writeFileSync } from 'node:fs'
import { runInNewContext } from 'node:vm'

const source = ['00-core.js', '10-script.js', '20-logo.js', '30-scene.js']
  .map((name) => readFileSync(new URL('../src/' + name, import.meta.url), 'utf8'))
  .join('\n')

const geometry = runInNewContext(source + '\n' + [
  'const scene = HS.sceneGeometry({ subtitle: true });',
  '({',
  '  canvas: HS.CANVAS, phases: HS.PHASES, colors: HS.RAINBOW,',
  '  left: scene.left, right: scene.right, fish: scene.fish, fishScale: scene.fishScale,',
  '  writing: scene.writing, ribbons: HS.buildRibbons(scene.strokes, scene.fish, scene.fishScale),',
  '  fishPath: HS.FISH_PATH,',
  '})',
].join('\n'))

const f = (number) => number.toFixed(5) + 'f'
const point = (x, y) => '{' + f(x) + ', ' + f(y) + '}'
const series = (points) => '{' + points.map(([x, y]) => point(x, y)).join(', ') + '}'
const valued = (values) => values.map(f).join(', ')
const path = geometry.fishPath.match(/[MCLZ]|-?\d*\.?\d+(?:[eE][-+]?\d+)?/g)
const logo = []
let repeated
for (let i = 0; i < path.length;) {
  const operation = /^[A-Z]$/.test(path[i]) ? path[i++] : repeated
  const count = { M: 2, L: 2, C: 6, Z: 0 }[operation]
  if (count === undefined) throw new Error('Unsupported whale command ' + operation)
  const values = path.slice(i, i + count).map(Number)
  if (values.length !== count || values.some((value) => !Number.isFinite(value))) {
    throw new Error('Invalid whale path')
  }
  const points = []
  for (let j = 0; j < count; j += 2) points.push(point(values[j], values[j + 1]))
  while (points.length < 3) points.push('{}')
  logo.push("    {'" + operation + "', " + points.join(', ') + '},')
  repeated = operation === 'M' ? 'L' : operation === 'Z' ? undefined : operation
  i += count
}

const { canvas, phases, left, right, fish, fishScale, writing, ribbons, colors } = geometry
const header = [
  '// Generated by dev/export-native-geometry.mjs. The values describe vector paths, not rendered frames.',
  '#pragma once',
  '',
  'namespace artwork {',
  'constexpr float kWidth = ' + f(canvas.width) + ';',
  'constexpr float kHeight = ' + f(canvas.height) + ';',
  'constexpr float kLeft = ' + f(left) + ';',
  'constexpr float kRight = ' + f(right) + ';',
  'constexpr float kLogoLeft = ' + f(fish.left) + ';',
  'constexpr float kLogoRight = ' + f(fish.left + fish.width) + ';',
  'constexpr float kLogoTop = ' + f(fish.top) + ';',
  'constexpr float kLogoScale = ' + f(fishScale) + ';',
  'constexpr float kSubtitleY = ' + f(fish.top + fish.height + 47) + ';',
  'constexpr float kWriteEnd = ' + f(phases.writeEnd) + ';',
  'constexpr float kMorphStart = ' + f(phases.holdEnd) + ';',
  'constexpr float kMorphEnd = ' + f(phases.morphEnd) + ';',
  'constexpr float kLogoHold = ' + f(phases.logoEnd) + ';',
  'constexpr unsigned kColors[] = {' + colors.map((color) => '0x' + color.slice(1)).join(', ') + '};',
  '',
  'constexpr size_t kPathPoints = ' + writing[0].points.length + ';',
  'struct Stroke { float start, end, width; D2D1_POINT_2F points[kPathPoints]; };',
  'constexpr Stroke kStrokes[] = {',
  ...writing.map(({ start, end, width, points }) => '    {' + valued([start, end, width]) + ', ' + series(points) + '},'),
  '};',
  '',
  'struct Ribbon { float width, delay, bend, twist; D2D1_POINT_2F from[kPathPoints], to[kPathPoints]; };',
  'constexpr Ribbon kRibbons[] = {',
  ...ribbons.map(({ width, delay, bend, twist, from, to }) =>
    '    {' + valued([width, delay, bend, twist]) + ', ' + series(from) + ', ' + series(to) + '},'),
  '};',
  '',
  'struct Segment { char kind; D2D1_POINT_2F a, b, c; };',
  'constexpr Segment kLogo[] = {',
  ...logo,
  '};',
  '} // namespace artwork',
  '',
].join('\n')
writeFileSync(new URL('../launcher/native/artwork.generated.h', import.meta.url), header)


