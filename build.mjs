/**
 * dsh-hello-splash · build step.
 *
 * The Client half must ship as one browser artifact in the DSH module-loader
 * format (`window.__ModuleLoader__.load`). Rather than pull in a bundler, the
 * source files under src/ are plain scripts that share one scope, and this
 * script concatenates them inside the loader factory. No dependencies, no
 * transpiling, and the built file stays readable.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)))
const srcDir = path.join(root, 'src')
const outFile = path.join(root, 'client.js')
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))

const order = fs
  .readdirSync(srcDir)
  .filter((file) => file.endsWith('.js'))
  .sort()

const parts = order.map((file) => {
  const body = fs.readFileSync(path.join(srcDir, file), 'utf8')
  // Strip the per-file banner comments; the bundle header lists the files instead.
  return `/* ===== src/${file} ===== */\n${body.trimEnd()}\n`
})

parts.unshift(fs.readFileSync(path.join(root, 'config.js'), 'utf8').replace(/^export /gm, ''))

const bundle = `/* dsh-hello-splash v${pkg.version} — generated by build.mjs; edit src/ instead. */
window.__ModuleLoader__.load({
  id: '${pkg.name}',
  factory: (require) => {
    const React = require('react')

${parts.join('\n').replace(/^/gm, '    ')}

    HS.React = React
    return {
      inject: ['slots'],
      apply: (ctx) => HS.apply(ctx),
    }
  },
})
`

fs.writeFileSync(outFile, bundle, 'utf8')
console.log(`built ${path.relative(root, outFile)} (${(bundle.length / 1024).toFixed(1)} KiB) from ${order.length} source files`)
console.log(order.map((file) => `  src/${file}`).join('\n'))
